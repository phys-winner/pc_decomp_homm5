"""Generate the x86 COM thunks and the typed native D3D9 dispatch of the DXVK renderer.

    python -X utf8 tools/generate_dxvk_bridge.py [--header PATH] [--check]

Both sides come from DXVK Native's pinned d3d9.h (reference/dxvk, imported by
tools/build_dxvk.py), so their interface kinds and slots cannot drift apart:
android/host/dxvk_methods.h is compiled into the ToE engine (android/host/d3d9_dxvk.c),
android/dxvk/bridge_*.h into libh5dxvk.so (android/dxvk/bridge.cpp). The outputs
are committed; --check fails when a regeneration would change them. Adapted from the
sibling ut3 port's tools/generate_dxvk_bridge.py.
"""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "reference/dxvk/include/native/directx/d3d9.h"
INTERFACES = ["IUnknown", "IDirect3D9", "IDirect3DDevice9", "IDirect3DResource9", "IDirect3DBaseTexture9",
              "IDirect3DTexture9", "IDirect3DCubeTexture9", "IDirect3DVolumeTexture9", "IDirect3DVolume9",
              "IDirect3DSurface9", "IDirect3DVertexBuffer9", "IDirect3DIndexBuffer9",
              "IDirect3DVertexDeclaration9", "IDirect3DVertexShader9", "IDirect3DPixelShader9",
              "IDirect3DStateBlock9", "IDirect3DQuery9", "IDirect3DSwapChain9"]
# Marshaled by hand in bridge.cpp: native pointers, HWNDs, guest-sized data or lock mappings.
# TestCooperativeLevel stays generic: a replaced Android surface never loses the device here.
SPECIAL = {"QueryInterface", "AddRef", "Release", "CreateDevice", "CreateAdditionalSwapChain", "Reset",
           "GetPresentParameters", "Present", "GetCreationParameters", "GetContainer", "Lock", "Unlock",
           "LockRect", "UnlockRect", "LockBox", "UnlockBox", "CreateVertexShader", "CreatePixelShader",
           "CreateVertexDeclaration", "DrawPrimitiveUP", "DrawIndexedPrimitiveUP", "GetFunction", "GetData",
           "GetPrivateData", "SetPrivateData", "FreePrivateData", "GetAdapterIdentifier", "GetAdapterMonitor",
           "GetDC", "ReleaseDC", "RegisterSoftwareDevice"}
PRIVATE_DATA = {"SetPrivateData", "GetPrivateData", "FreePrivateData"}
CREATES = {"CreateTexture", "CreateVolumeTexture", "CreateCubeTexture", "CreateVertexBuffer", "CreateIndexBuffer",
           "CreateRenderTarget", "CreateDepthStencilSurface", "CreateOffscreenPlainSurface"}
OUTPUTS = {
    "android/host/dxvk_methods.h": "c",
    "android/dxvk/bridge_metadata.h": "metadata",
    "android/dxvk/bridge_dispatch.h": "dispatch",
    "android/dxvk/bridge_special_names.h": "special",
}


def parse(source):
    methods = {}
    for interface in INTERFACES:
        if interface == "IUnknown":
            items = [("HRESULT", "QueryInterface", "REFIID iid, void** out"), ("ULONG", "AddRef", ""), ("ULONG", "Release", "")]
        else:
            found = re.search(r"DECLARE_INTERFACE_\(" + interface + r",\w+\)\s*\{(.*?)\n\};", source, re.S)
            if not found:
                raise ValueError("D3D9 interface not found: " + interface)
            items = []
            for match in re.finditer(r"STDMETHOD(?:_\(([^,]+),\s*(\w+)\)|\((\w+)\))\s*\(THIS(_)?\s*(.*?)\)\s*PURE;",
                                     found.group(1), re.S):
                result, name, hr_name, has_args, arguments = match.groups()
                items.append(((result or "HRESULT").strip(), name or hr_name, " ".join(arguments.split()) if has_args else ""))
        if [item[1] for item in items[:3]] != ["QueryInterface", "AddRef", "Release"]:
            raise ValueError("Invalid IUnknown prefix: " + interface)
        methods[interface] = items
    return methods


def argument_count(arguments):
    return 0 if not arguments else len(arguments.split(","))


def digest(methods):
    """FNV-1a over every interface's slot names and stack sizes: the host and the
    bridge refuse each other unless both were generated from the same table."""
    value = 0x811C9DC5
    for interface in INTERFACES:
        text = interface + ":" + ",".join(f"{name}/{argument_count(arguments)}" for _, name, arguments in methods[interface]) + ";"
        for byte in text.encode():
            value = ((value ^ byte) * 0x01000193) & 0xFFFFFFFF
    return value


def render(methods):
    value = digest(methods)
    banner = "/* Generated by tools/generate_dxvk_bridge.py from DXVK Native's d3d9.h; do not edit. */"
    c = [banner, "/* Included by android/host/d3d9_dxvk.c: one stdcall thunk per guest-visible slot. */",
         f"#define DXVK_SLOTS_DIGEST 0x{value:08X}u"]
    for kind, interface in enumerate(INTERFACES):
        for slot, (result, name, arguments) in enumerate(methods[interface]):
            count = argument_count(arguments)
            assert count <= 14, (interface, name, count)
            finish = "dxvk_return_float(result);" if result == "float" else "g_eax = result;"
            values = ", ".join(f"ARG({i + 1})" for i in range(count)) if count else "0"
            c.append(f"static void dxvk_{kind}_{slot}(void) {{ uint32_t a[{max(count, 1)}] = {{{values}}}; "
                     f"uint32_t result = dxvk_guest_call(THIS_, {kind}u, {slot}u, a); {finish} g_esp += {8 + 4 * count}u; }}")
        c.append(f"static const void_fn dxvk_methods_{kind}[] = {{" +
                 ", ".join(f"dxvk_{kind}_{slot}" for slot in range(len(methods[interface]))) + "};")
    c.append("static void_com_class dxvk_classes[] = {")
    c += [f'    {{"DXVK::{interface}", {len(methods[interface])}, dxvk_methods_{kind}, 0}},' for kind, interface in enumerate(INTERFACES)]
    c.append("};")
    metadata = [banner, "/* Typed native D3D9 kinds; the numbering is shared with android/host/dxvk_methods.h. */",
                "enum class Kind : unsigned {" + ",".join(INTERFACES) + ",Count};",
                f"static constexpr uint32_t kSlotsDigest = 0x{value:08X}u;",
                "template<class T> struct KindOf;", "static Kind kind_for_iid(REFIID iid) {"]
    metadata += [f"  if (iid == __uuidof({name})) return Kind::{name};" for name in INTERFACES]
    metadata += ["  return Kind::Count;", "}"]
    metadata += [f"template<> struct KindOf<{interface}> {{ static constexpr Kind value = Kind::{interface}; }};" for interface in INTERFACES]
    dispatch, special = [banner], [banner]
    for interface in INTERFACES:
        dispatch.append(f"case Kind::{interface}: switch (slot) {{")
        special.append(f"case Kind::{interface}: switch (slot) {{")
        for slot, (result, name, arguments) in enumerate(methods[interface]):
            if name in SPECIAL:
                if name in PRIVATE_DATA:
                    dispatch.append(f'  case {slot}: return private_data(c, static_cast<{interface}*>(c.self), "{name}");')
                else:
                    special.append(f'  case {slot}: name = "{name}"; break;')
                continue
            helper = "create_resource" if name in CREATES else "invoke"
            dispatch.append(f'  case {slot}: return {helper}(c, &{interface}::{name}, "{name}");')
        dispatch.append("  default: break;\n} break;")
        special.append("  default: break;\n} break;")
    return {"c": c, "metadata": metadata, "dispatch": dispatch, "special": special}


def outputs(header=HEADER):
    methods = parse(Path(header).read_text(encoding="utf-8"))
    rendered = render(methods)
    return {relative: ("\n".join(rendered[part]) + "\n").encode() for relative, part in OUTPUTS.items()}, methods


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--header", type=Path, default=HEADER, help="DXVK Native include/native/directx/d3d9.h")
    parser.add_argument("--check", action="store_true", help="fail if the committed outputs are stale")
    args = parser.parse_args()
    if not args.header.is_file():
        parser.error(f"{args.header} is missing; run tools/build_dxvk.py (it imports the pinned DXVK headers)")
    generated, methods = outputs(args.header)
    stale = []
    for relative, data in generated.items():
        path = ROOT / relative
        current = path.read_bytes().replace(b"\r\n", b"\n") if path.is_file() else None
        if current != data:
            stale.append(relative)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
    if args.check and stale:
        sys.exit("Stale DXVK bridge outputs (run tools/generate_dxvk_bridge.py): " + ", ".join(stale))
    print(f"{sum(len(items) for items in methods.values())} D3D9 slots across {len(methods)} interfaces, "
          f"digest {digest(methods):08X}; {'stale: ' + ', '.join(stale) if stale else 'outputs current'}")


if __name__ == "__main__":
    main()
