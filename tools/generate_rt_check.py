"""Write android/host/d3d9_thread_check.inc: every GL/EGL function the D3D9 files call,
wrapped to check first that it runs on the render thread (built with --rt-check)."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
HOST = ROOT / "android/host"
SOURCES = ["d3d9_gl.c", "d3d9_resource.c", "d3d9_shader.c", "d3d9_ff.c", "d3d9_device.c", "d3d9_filter.c"]
ANY_THREAD = {"eglGetProcAddress"}


def main():
    names = set()
    for name in SOURCES:
        text = (HOST / name).read_text(encoding="utf-8")
        names.update(re.findall(r"\b((?:gl|egl)[A-Z]\w*)\s*\(", text))
    names -= ANY_THREAD
    lines = ["/* Generated by tools/generate_rt_check.py: GL and EGL calls of the D3D9 files, each",
             " * checked to run where the context lives (d3d9_thread.inc, VOID_RT_CHECK). */"]
    for fn in sorted(names):
        lines.append(f'#define {fn}(...) (d3d_rt_gl_check("{fn}"), {fn}(__VA_ARGS__))')
    out = HOST / "d3d9_thread_check.inc"
    out.write_bytes(("\n".join(lines) + "\n").encode())
    print(f"{out}: {len(names)} functions")


if __name__ == "__main__":
    main()
